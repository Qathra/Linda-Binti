def esc(s: str) -> str:
    return (s.replace("&", "&amp;")
             .replace("'", "\\'")
             .replace('"', '\\"'))

def main() -> None:
    en_text = EN.read_text(encoding="utf-8")
    names = re.findall(r'<string\s+name="([^"]+)"', en_text)
    missing = [n for n in names if n not in T]
    if missing:
        raise SystemExit(f"Missing {len(missing)} translations: {missing[:20]} ...")

    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
    for name in names:
        val = T[name]
        # preserve &amp; from source where already encoded
        lines.append(f'    <string name="{name}">{val}</string>')
    lines.append("</resources>")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(names)} strings to {OUT}")

if __name__ == "__main__":
    main()
